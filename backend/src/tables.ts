/** Level reached with `xp` given a table of per-level XP requirements, up to `cap` */
export function levelFromTable(xp: number, table: number[], cap: number, offset = 0): number {
  let remaining = xp;
  let level = 0;
  while (level < cap && offset + level < table.length && remaining >= table[offset + level]) {
    remaining -= table[offset + level];
    level++;
  }
  return level;
}
