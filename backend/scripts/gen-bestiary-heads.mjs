// Regenerates src/bestiary-heads.ts from SkyCrypt's bestiary data: node scripts/gen-bestiary-heads.mjs
// The downloaded file is only parsed as text, never executed.
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/SkyCryptWebsite/SkyCrypt/development/src/constants/bestiary.js';
const text = await (await fetch(SOURCE)).text();

// A mob entry: texture "/head/<hash>" followed by a `mobs` array holding only string keys
const ENTRY = /texture:\s*"\/head\/([0-9a-f]+)",\s*mobs:\s*\[((?:\s*"[^"]*"\s*,?)*)\s*\]/g;

const heads = {};
for (const [, hash, keys] of text.matchAll(ENTRY)) {
  for (const [, key] of keys.matchAll(/"([^"]*)"/g)) {
    heads[key] = hash;
  }
}

const body = Object.keys(heads).sort().map(k => `  ${k}: '${heads[k]}',`).join('\n');
writeFileSync(new URL('../src/bestiary-heads.ts', import.meta.url),
  `// Generated by scripts/gen-bestiary-heads.mjs from SkyCrypt's bestiary data; do not edit\nexport const BESTIARY_HEADS: Record<string, string> = {\n${body}\n};\n`);
console.log(`${Object.keys(heads).length} mobs`);
